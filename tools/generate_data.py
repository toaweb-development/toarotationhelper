#!/usr/bin/env python3
"""Generates Data/<Class>.lua from WoW Forever game data.

Sources (see README "Rotation research"):
  - MythicSim Forever engine data (spells.jsonl): ranks, levels, mana cost, cast time, duration.
    https://github.com/sage3648/mythicsim-forever-engine  (MIT)
  - Forever client SpellCooldowns table, extracted from the local install with SimulationCraft's
    casc_extract.py (--product wowf) and dumped to CSV with dbc_extract.py.

Usage:
  python3 tools/generate_data.py ~/tools/mythicsim-forever-engine ~/tools/forever_data/SpellCooldowns.csv

The output is plain data; no logic lives in Data/ (§wow-addon/structure).
"""
import csv
import json
import os
import sys

# family key -> (spell name, extra filter)
PRIEST = {
    'smite': 'Smite',
    'swp': 'Shadow Word: Pain',
    'holyfire': 'Holy Fire',
    'mindblast': 'Mind Blast',
    'devouringplague': 'Devouring Plague',
    'mindflay': 'Mind Flay',
    'swdeath': 'Shadow Word: Death',
    'innerfocus': 'Inner Focus',
    'shadowform': 'Shadowform',
    'penance': 'Penance',
}
# Channelled spells: the player is busy for the channel, not a cast time.
CHANNELS = {'mindflay', 'penance'}
# Talents that change what the tracker or the rotation choice must know.
# key -> (talent spell id, max rank, kind, families, divisor)
# The client row's first effect holds the value at max rank (MythicSim: Ladder::talent(id, max)); the
# tracker scales it by rank / max. Kinds: duration / cast / cooldown (seconds, divisor 1000 from ms),
# costPct (percent), flag (only the rank matters: the rotation choice reads it).
PRIEST_TALENTS = {
    'improvedSwp': (15275, 2, 'duration', ['swp'], 1000),
    'divineFury': (18530, 5, 'cast', ['smite', 'holyfire'], 1000),
    'improvedMindBlast': (15273, 5, 'cooldown', ['mindblast'], 1000),
    'mentalAgility': (14520, 3, 'costPct', ['swp', 'devouringplague', 'swdeath'], 1),
    'wandSpecialization': (14524, 2, 'flag', [], 1),
    'searingLight': (14909, 2, 'flag', [], 1),
}


def rank_number(rank):
    if not rank or not rank.startswith('Rank '):
        return None
    try:
        return int(rank.split()[1])
    except ValueError:
        return None


def main(mythicsim_dir, cooldown_csv, out_dir):
    spells = {}
    by_name = {}
    with open(os.path.join(mythicsim_dir, 'data', 'spells.jsonl')) as f:
        for line in f:
            s = json.loads(line)
            spells[s['ID']] = s
            by_name.setdefault(s['Name'], []).append(s)

    cooldowns = {}
    with open(cooldown_csv) as f:
        for row in csv.DictReader(f):
            parent = int(row['id_parent'])
            cd = max(int(row['cooldown'] or 0), int(row['category_cooldown'] or 0))
            cooldowns[parent] = (cd, int(row['gcd_cooldown'] or 0))

    def cost_of(s):
        for p in s.get('Powers') or []:
            if 'Cost' in p:
                return p['Cost']
        return 0

    def castable(s):
        # Skip helper rows (triggered bolts, hidden passives): a player-cast rank has a cost or a
        # cooldown row, and Penance's cast row is the one with a mana cost.
        if s.get('ClassFlags', {}).get('Family') not in (6, None):
            return False
        if s['Name'] == 'Penance':
            return cost_of(s) > 0
        return s['ID'] in cooldowns or cost_of(s) > 0

    lines = [
        '-- Generated by tools/generate_data.py from WoW Forever game data. Do not edit by hand.',
        '-- Sources: MythicSim Forever engine data (MIT) and the Forever client SpellCooldowns table.',
        'local _, ns = ...',
        '',
        'ns.Data = ns.Data or {}',
        'ns.Data.PRIEST = {',
        '\tspells = {',
    ]
    for key, name in PRIEST.items():
        rows = [s for s in by_name.get(name, []) if castable(s)]
        # A ranked family drops unranked variants (other game modes' versions of the spell).
        if any(rank_number(s.get('Rank')) for s in rows):
            rows = [s for s in rows if rank_number(s.get('Rank'))]
        rows.sort(key=lambda s: (s.get('SpellLevel') or 0, rank_number(s.get('Rank')) or 0))
        if not rows:
            print(f'warning: no rows for {name}', file=sys.stderr)
            continue
        top = rows[-1]
        cd_ms, gcd_ms = cooldowns.get(top['ID'], (0, top.get('GCDMs') or 1500))
        duration = top.get('DurationMs') or 0
        if duration < 0:
            duration = 0
        lines.append(f'\t\t{key} = {{')
        lines.append(f'\t\t\tname = "{name}",')
        lines.append(f'\t\t\tcooldown = {cd_ms / 1000:g},')
        lines.append(f'\t\t\tgcd = {(gcd_ms or 0) / 1000:g},')
        lines.append(f'\t\t\tduration = {duration / 1000:g},')
        if key in CHANNELS:
            lines.append('\t\t\tchannel = true,')
        lines.append('\t\t\tranks = {')
        for s in rows:
            cast = (s.get('CastTimeMs') or 0) / 1000
            if key in CHANNELS:
                # Busy time is the channel; Penance's cast row has no duration, its bolt rows have 2 s.
                cast = (s.get('DurationMs') or 2000) / 1000
            lines.append(
                f'\t\t\t\t{{ id = {s["ID"]}, rank = {rank_number(s.get("Rank")) or 0}, '
                f'level = {s.get("SpellLevel") or 1}, cost = {cost_of(s)}, cast = {cast:g} }},'
            )
        lines.append('\t\t\t},')
        lines.append('\t\t},')
    lines.append('\t},')

    # Talents: spell IDs per rank and the per-rank effect value from the client row.
    lines.append('\ttalents = {')
    for key, (talent_id, max_rank, kind, families, divisor) in PRIEST_TALENTS.items():
        row = spells.get(talent_id)
        if not row:
            print(f'warning: no talent row {talent_id} for {key}', file=sys.stderr)
            continue
        value = 0
        for e in row.get('Effects') or []:
            value = e.get('BasePoints') or 0
            break
        fams = ', '.join(f'"{f}"' for f in families)
        lines.append(
            f'\t\t{key} = {{ name = "{row["Name"]}", id = {talent_id}, maxRank = {max_rank}, '
            f'kind = "{kind}", families = {{ {fams} }}, valueAtMax = {value / divisor:g} }},'
        )
    lines.append('\t},')
    lines.append('}')

    out = os.path.join(out_dir, 'Data', 'Priest.lua')
    os.makedirs(os.path.dirname(out), exist_ok=True)
    with open(out, 'w') as f:
        f.write('\n'.join(lines) + '\n')
    print(f'wrote {out}')


if __name__ == '__main__':
    if len(sys.argv) != 3:
        print(__doc__)
        sys.exit(1)
    addon_dir = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
    main(os.path.expanduser(sys.argv[1]), os.path.expanduser(sys.argv[2]), addon_dir)
